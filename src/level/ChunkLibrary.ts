export interface Chunk {
  name: string;
  entryY: number;
  exitY: number;
  layout: readonly string[];
  world?: 0 | 1 | 2;
  fireRain?: boolean;
}

interface ChunkOptions {
  entryY?: number;
  exitY?: number;
  world?: 0 | 1 | 2;
  fireRain?: boolean;
}

function chunk(name: string, floor: string, objects: Readonly<Record<number, string>>, opts: ChunkOptions = {}): Chunk {
  const { entryY = 13, exitY = 13, world, fireRain } = opts;
  const layout = Array.from({ length: 15 }, () => Array<string>(floor.length).fill('.'));
  for (let x = 0; x < floor.length; x++) {
    const top = floor[x] === '-' ? 15 : 13 - Number(floor[x]);
    for (let y = top; y < 15; y++) layout[y][x] = '#';
  }
  for (const [row, line] of Object.entries(objects)) {
    if (line.length > floor.length) throw new Error('区块对象越界 ' + name);
    for (let x = 0; x < line.length; x++) if (line[x] !== '.') layout[Number(row)][x] = line[x];
  }
  return { name, entryY, exitY, world, fireRain, layout: layout.map(row => row.join('')) };
}

